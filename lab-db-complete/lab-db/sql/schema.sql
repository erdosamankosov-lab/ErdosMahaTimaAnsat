-- Re-runnable PostgreSQL schema for the learning center.
DROP TABLE IF EXISTS enrollments CASCADE;
DROP TABLE IF EXISTS courses CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TABLE IF EXISTS teachers CASCADE;

CREATE TABLE teachers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  CONSTRAINT teachers_name_nonempty CHECK (length(btrim(full_name)) > 0),
  CONSTRAINT teachers_email_nonempty CHECK (length(btrim(email)) > 0)
);

CREATE TABLE students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  student_group VARCHAR(50) NOT NULL,
  CONSTRAINT students_name_nonempty CHECK (length(btrim(full_name)) > 0),
  CONSTRAINT students_email_nonempty CHECK (length(btrim(email)) > 0),
  CONSTRAINT students_group_nonempty CHECK (length(btrim(student_group)) > 0)
);

CREATE TABLE courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  hours INTEGER NOT NULL CHECK (hours > 0),
  teacher_id INTEGER NOT NULL REFERENCES teachers(id) ON DELETE RESTRICT,
  CONSTRAINT courses_title_nonempty CHECK (length(btrim(title)) > 0)
);

CREATE TABLE enrollments (
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  enrolled_at DATE NOT NULL DEFAULT CURRENT_DATE,
  grade INTEGER CHECK (grade BETWEEN 0 AND 100),
  PRIMARY KEY (student_id, course_id)
);
